_SUFFIX = re.compile(r"(방면|방향|쪽|행|시|군|IC|JC|나들목|분기점|톨게이트|TG)$")


def normalize(name: str) -> str:
    n = name.strip()
    n = re.sub(r"[\s·()\[\]0-9.]+", "", n)
    prev = None
    while prev != n:
        prev, n = n, _SUFFIX.sub("", n)
    return n


def _cache_path():
    return get_settings().data_dir / "geocode_cache.json"


def _load_cache() -> dict:
    try:
        return json.loads(_cache_path().read_text())
    except Exception:
        return {}


def geocode(name: str | None) -> tuple[float, float] | None:
    if not name or not name.strip():
        return None
    key = normalize(name)
    if not key:
        return None
    if key in KNOWN:
        return KNOWN[key]
    with _lock:
        cache = _load_cache()
        if key in cache:
            v = cache[key]
            return (v[0], v[1]) if v else None
        coord = None
        try:
            r = httpx.get(
                "https://nominatim.openstreetmap.org/search",
                params={"q": key, "countrycodes": "kr", "format": "json", "limit": 1, "accept-language": "ko"},
                headers={"User-Agent": "traffic-occupancy-monitor/1.0 (academic project)"},
                timeout=10,
            )
            if r.status_code == 200 and r.json():
                j = r.json()[0]
                coord = (float(j["lat"]), float(j["lon"]))
        except Exception as e:
            log.warning("지오코딩 실패(%s): %s", key, e)
            return None  # 네트워크 오류는 캐시하지 않는다
        cache[key] = list(coord) if coord else None
        try:
            _cache_path().write_text(json.dumps(cache, ensure_ascii=False))
        except Exception:
            pass
        return coord
